SPLIT = re.compile(r"\b(?:L10n\.t|Loc\.T)\(\s*" + LITERAL + r"\s*\+")


def placeholders(text):
    return set(PLACEHOLDER.findall(text))


def no_duplicates(pairs):
    out = {}
    for key, value in pairs:
        if key in out:
            sys.exit(f"duplicate key: {key!r}")
        out[key] = value
    return out


def read_json(path):
    return json.loads(path.read_text(encoding="utf-8"), object_pairs_hook=no_duplicates)


def catalog():
    """(strings, infoplist) of shared.json."""
    data = read_json(CATALOG)
    return data, data.pop("infoplist", {"ios": {}, "mac": {}})


def categories(rules):
    """Categories a translation must cover. many is kept only with a real integer sample."""
    out = []
    for name in CATEGORIES:
        if name not in rules:
            continue
        samples = [s.strip() for s in rules[name].get("integer", "").split(",")]
        if name == "other" or any(s and "c" not in s and s != "…" for s in samples):
            out.append(name)
    return out


def languages():
    entries = read_json(LANGUAGE_LIST)
    plural = read_json(PLURAL_RULES)
    errors = []
    known = {e["code"] for e in entries}
    for path in sorted(LANG_DIR.glob("*.json")):
        if path.stem not in known:
            errors.append(f"{path.name}: not a code in languages.json")
    for entry in entries:
        code = entry["code"]
        if code not in plural:
            errors.append(f"{code}: no entry in plural.json")
        elif entry["plural"] != categories(plural[code]):
            errors.append(f"{code}: plural {','.join(entry['plural'])} differs from plural.json {','.join(categories(plural[code]))}")
    if errors:
        sys.exit("\n".join(errors))
    return {e["code"]: e for e in entries}


INFO = languages()
LANGUAGES = [code for code in INFO if (LANG_DIR / f"{code}.json").exists()]


def lang_doc(code):
    path = LANG_DIR / f"{code}.json"
    return read_json(path) if path.exists() else {"strings": {}}


def check_doc(code):
    doc = lang_doc(code)
    errors = []
    if not isinstance(doc, dict) or not isinstance(doc.get("strings", {}), dict) or not isinstance(doc.get("views", {}), dict)             or not isinstance(doc.get("win", {}), dict):
        return [f"{code}: strings, views and win must be objects"]
    plist = doc.get("infoplist", {})
    if not isinstance(plist, dict) or set(plist) - {"ios", "mac"} or not all(isinstance(v, dict) for v in plist.values()):
        errors.append(f"{code}: infoplist holds an ios and a mac object only")
    return errors


def integer_samples(lang, category):
    rules = read_json(PLURAL_RULES)[lang].get(category, {})
    return [s.strip() for s in rules.get("integer", "").split(",") if s.strip()]


def single_sample(lang, category):
    samples = integer_samples(lang, category)
    return len(samples) == 1 and "~" not in samples[0] and samples[0] != "…"


def required_categories(lang):
    """Categories a file must hold. many stays optional where its integer samples are only millions."""
    def millions(category):
        return all(s == "…" or "c" in s or s == "1000000" for s in integer_samples(lang, category))

    return [c for c in INFO[lang]["plural"] if c != "many" or not millions(c)]


def check_catalog(data):
    errors = []
    names = {}
    for key, entry in data.items():
        if not isinstance(entry, dict) or set(entry) - {"other", "note", "same"}:
            errors.append(f"{key!r}: an entry holds other, note and same only")
            continue
        if "other" in entry and not (isinstance(entry["other"], str) and entry["other"].strip()):
            errors.append(f"{key!r}: other must be text")
        if MARKER.search(key):
            errors.append(f"{key!r}: ends like a plural row name")
        forms = [key + "|" + c for c in CATEGORIES] if "other" in entry else [key]
        for name in forms:
            if names.setdefault(name.lower(), key) != key:
                errors.append(f"{key!r}: resx name collides with {names[name.lower()]!r} ignoring case")
    return errors


def view_keys():
    """key -> the platforms whose list holds it, in list order."""
    out = {}
    for platform, path in KEY_LISTS.items():
        for entry in read_json(path)["keys"]:
            out.setdefault(entry["key"], set()).add(platform)
    return out


def view_notes():
    return read_json(KEY_NOTES)


def specifiers(text):
    """(position or None, type) of each format specifier, in order."""
    return [m.groups() for m in SPECIFIER.finditer(text.replace("%%", ""))]


def words(text):
    """Whether text holds letters once format specifiers and names that read the same everywhere are gone."""
    return bool(LETTER.search(TOKENS.sub("", SPECIFIER.sub("", text.replace("%%", "")))))


def format_problem(key, value):
    """Why value cannot stand for key as a format string, else None. The arguments arrive in key order, so a
    plain value must repeat the key's types in order and a positional one must map each N$ to the type at slot N."""
    want = [t for _, t in specifiers(key)]
    got = specifiers(value)
    if "%" in SPECIFIER.sub("", value.replace("%%", "")):
        return "has a stray %"
    positions = [p for p, _ in got]
    if all(p is None for p in positions):
        return None if [t for _, t in got] == want else f"has the specifiers {[t for _, t in got]}, the key has {want} in this order"
    if any(p is None for p in positions):
        return "mixes positional and plain specifiers"
    for p, t in got:
        if not 1 <= int(p) <= len(want) or want[int(p) - 1] != t:
            return f"has %{p}${t}, which does not match slot {p} of the key {want}"
    if {int(p) for p in positions} != set(range(1, len(want) + 1)):
        return f"leaves a slot of the key {want} unused"
    return None


def view_text(key, strings, views):
    """The value of a view key: its views entry, else the strings value of an identical key without specifiers."""
    if key in views:
        return views[key]
    value = strings.get(key)
    return value if isinstance(value, str) and not specifiers(key) else None


def english_view(key):
    match = CONTEXT_SUFFIX.search(key)
    return key[:match.start() + 1] if match else key


def check_views(lang, views, keys):
    """(errors, count of values equal to English). A key without specifiers holds a literal %, so any value is fine."""
    errors, same = [], 0
    for key, value in views.items():
        label = f"view {key!r}: {lang}"
        if key not in keys:
            errors.append(f"{label} is not in a key list")
        elif not (isinstance(value, str) and value.strip()):
            errors.append(f"{label} must be text")
        else:
            problem = specifiers(key) and format_problem(key, value)
            if problem:
                errors.append(f"{label} {problem}")
            if placeholders(value) != placeholders(key):
                errors.append(f"{label} has the placeholders {sorted(placeholders(value))}, the key has {sorted(placeholders(key))}")
            if CONTEXT_SUFFIX.search(value):
                errors.append(f"{label} ends in a |context suffix")
            if value == english_view(key):
                if INFO[lang]["latin"]:
                    same += 1
                elif words(value):
                    errors.append(f"{label} is the English text")
    return errors, same


def plist_source(platform):
    if platform == "ios":
        return IOS_PLIST.read_text(encoding="utf-8")
    return re.search(r"<<'PLIST'\n(.*?)\nPLIST\n", MAC_PLIST.read_text(encoding="utf-8"), re.S).group(1)


def check_plist_catalog(plist):
    if not isinstance(plist, dict) or set(plist) != {"ios", "mac"}:
        return ["infoplist holds an ios and a mac object"]
    errors = []
    for platform, entries in plist.items():
        source = plist_source(platform)
        for key, text in entries.items():
            if not (isinstance(text, str) and text.strip()):
                errors.append(f"infoplist {platform} {key!r}: must be text")
            elif f"<key>{key}</key>" not in source and not re.search(
                    r"<key>CFBundleTypeName</key>\s*<string>" + re.escape(key) + "</string>", source):
                errors.append(f"infoplist {platform} {key!r}: is not a key or a CFBundleTypeName in the Info.plist")
    return errors


def check_infoplist(lang, plist, table):
    errors = []
    for platform, entries in table.items():
        for key, value in entries.items():
            label = f"infoplist {platform} {key!r}: {lang}"
            if key not in plist[platform]:
                errors.append(f"{label} has no English entry")
            elif not (isinstance(value, str) and value.strip()):
                errors.append(f"{label} must be text")
            elif value == plist[platform][key] and not INFO[lang]["latin"] and LETTER.search(TOKENS.sub("", value)):
                errors.append(f"{label} is the English text")
    return errors


def check_text(value, want, omit_zero):
    if not isinstance(value, str):
        return ["must be a string"]
    if not value.strip():
        return ["is empty"]
    problems = []
    if re.search(r"[{}]", PLACEHOLDER.sub("", value)):
        problems.append("has an unbalanced brace")
    if CONTEXT_SUFFIX.search(value):
        problems.append("ends in a |context suffix")
    got = placeholders(value)
    if got != want and not (omit_zero and got == want - {"0"}):
        problems.append(f"placeholders {sorted(got)} differ from English {sorted(want)}")
    return problems


def strip_context(text):
    return text.rsplit("|", 1)[0]


def edges(text):
    return text[:len(text) - len(text.lstrip())], text[len(text.rstrip()):]


def check_language(data, lang, strings):
    """(errors, warnings, count of values equal to English) for one table."""
    errors, warnings, same = [], [], 0
    info = INFO[lang]
    required = required_categories(lang)

    def check_value(key, entry, value, english, category, want, omit_zero):
        nonlocal same
        label = f"{key!r}: {lang}" + (f" {category}" if category else "")
        problems = check_text(value, want, omit_zero)
        errors.extend(f"{label} {p}" for p in problems)
        if not isinstance(value, str) or not value.strip():
            return
        english = strip_context(english)
        if value == english:
            if info["latin"]:
                same += 1
            elif not (entry.get("same") is True or not LETTER.search(TOKENS.sub("", value))):
                errors.append(f"{label} is the English text")
        if value.count("\n") != english.count("\n"):
            warnings.append(f"{label} has a different number of line breaks")
        if edges(value) != edges(english):
            warnings.append(f"{label} has different leading or trailing whitespace")

    for key, value in strings.items():
        if key not in data:
            errors.append(f"{key!r}: {lang} has no English entry")
            continue
        entry = data[key]
        if "other" not in entry:
            check_value(key, entry, value, key, None, placeholders(key), False)
            continue
        if not isinstance(value, dict):
            errors.append(f"{key!r}: {lang} must hold the plural categories")
            continue
        for category in required:
            if category not in value:
                errors.append(f"{key!r}: {lang} lacks {category}")
        for category, text in value.items():
            if category not in info["plural"]:
                errors.append(f"{key!r}: {lang} has the unknown category {category}")
                continue
            check_value(key, entry, text, key if category == "one" else entry["other"], category,
                        placeholders(entry["other"]), single_sample(lang, category))
    return errors, warnings, same


def load():
    data, plist = catalog()
    errors = check_catalog(data) + check_plist_catalog(plist)
    keys = view_keys()
    errors += [f"keys-notes.json: {key!r} is not in a key list" for key in view_notes() if key not in keys]
    tables, infos, views, warnings = {}, {}, {}, []
    for lang in LANGUAGES:
        doc_errors = check_doc(lang)
        if doc_errors:
            errors += doc_errors
            continue
        doc = lang_doc(lang)
        tables[lang] = doc.get("strings", {})
        infos[lang] = {"ios": {}, "mac": {}, **doc.get("infoplist", {})}
        views[lang] = doc.get("views", {})
        errors += check_infoplist(lang, plist, infos[lang])
        found, warned, same = check_language(data, lang, tables[lang])
        errors += found
        warnings += warned
        found, warned, _ = check_language(data, lang, doc.get("win", {}))
        errors += [e.replace(f": {lang}", f": {lang} win", 1) for e in found]
        warnings += warned
        found, view_same = check_views(lang, views[lang], keys)
        errors += found
        if same + view_same:
            warnings.append(f"{lang}: {same + view_same} values are the same as English")
    for line in warnings:
        print("warning: " + line, file=sys.stderr)
    if errors:
        sys.exit("\n".join(errors))
    return data, plist, tables, infos, views


def rows(data, tables, lang):
    """(key, text) pairs for one language; English is the keys themselves."""
    for key in data:
        if lang == "en":
            if "other" in data[key]:
                yield f"{key}|one", strip_context(key)
                yield f"{key}|other", strip_context(data[key]["other"])
            else:
                yield key, strip_context(key)
            continue
        value = tables[lang].get(key)
        if value is None:
            continue
        if isinstance(value, dict):
            for category in CATEGORIES:
                if category in value:
                    yield f"{key}|{category}", value[category]
        else:
            yield key, value


def object_text(value, order, indent):
    """The entries of an object, one per line, in `order` first; keys it lacks follow."""
    position = {key: i for i, key in enumerate(order)}
    pad = " " * indent
    body = ",\n".join(f"{pad}{json.dumps(k, ensure_ascii=False)}: {json.dumps(value[k], ensure_ascii=False)}"
                      for k in sorted(value, key=lambda k: position.get(k, len(position))))
    return f"{{\n{body}\n{pad[:-2]}}}" if value else "{}"


def lang_text(doc, order, plist_order, view_order):
    """A lang file with the strings in catalog order and the views in key list order, one entry per line."""
    out = []
    for name in doc:
        value = doc[name]
        if name == "infoplist":
            text = "{\n" + ",\n".join(f"    {json.dumps(p)}: {object_text(v, plist_order[p], 6)}" for p, v in value.items()) + "\n  }"
        elif isinstance(value, dict):
            text = object_text(value, {"strings": order, "win": order, "views": view_order}.get(name, []), 4)
        else:
            text = json.dumps(value, ensure_ascii=False)
        out.append(f"  {json.dumps(name)}: {text}")
    return "{\n" + ",\n".join(out) + "\n}\n"


def format_languages(prune):
    data, plist = catalog()
    keys = view_keys()
    for lang in LANGUAGES:
        doc = lang_doc(lang)
        if prune:
            for key in [k for k in doc["strings"] if k not in data]:
                del doc["strings"][key]
                print(f"{lang}: removed {key!r}")
            for key in [k for k in doc.get("win", {}) if k not in data]:
                del doc["win"][key]
                print(f"{lang}: removed win {key!r}")
            for key in [k for k in doc.get("views", {}) if k not in keys]:
                del doc["views"][key]
                print(f"{lang}: removed view {key!r}")
            for platform, entries in doc.get("infoplist", {}).items():
                for key in [k for k in entries if k not in plist[platform]]:
                    del entries[key]
                    print(f"{lang}: removed {platform} {key!r}")
        write(LANG_DIR / f"{lang}.json", lang_text(doc, list(data), {p: list(e) for p, e in plist.items()}, list(keys)))


# How a key is shown: from its context suffix, else the line that holds it, else its file and shape.
CONTEXT_CLASS = {"button": "button", "page button": "button", "photocopy button": "button", "step": "chip",
                 "tab": "tab", "section": "heading", "print job name": "file name", "after another fact": "status",
                 "scanner source": "chip", "color mode": "chip", "format": "chip", "enhance": "chip", "page option": "chip",
                 "page gap": "chip", "password field": "label", "lowercase label": "label", "noun": "label"}
CALL_CLASS = [(re.compile(r"accessibility(?:Label|Hint|Value)|AutomationProperties|Speak"), "spoken"),
              (re.compile(r"\.help\(|ToolTip"), "tooltip"),
              (re.compile(r"\bTab\(|\.tabItem|TabItem"), "tab"),
              (re.compile(r"\bButton\b|MenuItem|ToggleButton|UIAlertAction|\.confirmationDialog"), "button"),
              (re.compile(r"navigationTitle|\bSection\(|GroupBox|Expander"), "heading"),
              (re.compile(r"\b(?:Toggle|Picker|TextField|SecureField|LabeledContent|Label)\b|CheckBox|ComboBox|TextBox"), "label")]
STATUS_FILES = re.compile(r"AppState|StatusLine|ViewModel|PhotoImport|\.xaml\.cs$")
# Width budgets in characters: a compact surface has a fixed one, the rest grow with the English text.
BUDGET = {"button": 20, "chip": 14, "tab": 12, "tile": 24, "heading": 28, "label": 28, "file name": 24}


def read_source(path):
    """A source file with Swift's braced unicode escapes written out, as the keys hold them."""
    text = path.read_text(encoding="utf-8", errors="ignore")
    return re.sub(r"\\u\{([0-9A-Fa-f]+)\}", lambda m: chr(int(m.group(1), 16)), text)


def literal(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


def source_line(text, key, xaml):
    """The line of text that holds key as a string literal (a XAML attribute for xaml, with the line above, where
    the element tag sits), or empty."""
    if xaml:
        needle = html.escape(key.split("{")[0], quote=False)[:30]
        at = max(text.find("loc:T " + needle), text.find(needle)) if needle else -1
    elif SPECIFIER.search(key):
        parts = [re.escape(literal(p)[1:-1]) for p in SPECIFIER.split(key)[::3]]
        match = re.search('"' + r"\\\(.*?\)".join(parts) + '"', text)
        at = match.start() if match else -1
    else:
        at = text.find(literal(key))
    if at < 0:
        return ""
    start = text.rfind("\n", 0, at) + 1
    if xaml:
        start = text.rfind("\n", 0, max(start - 1, 0)) + 1
    end = text.find("\n", at)
    return text[start:] if end < 0 else text[start:end]


def surface(key, line, rel):
    """(screen, class, budget) of one key. The screen is the name of its file."""
    text = english_view(key)
    context = CONTEXT_SUFFIX.search(key)
    kind = CONTEXT_CLASS.get(key[context.start() + 2:]) if context else None
    kind = kind or next((c for pattern, c in CALL_CLASS if pattern.search(line)), None)
    stem = Path(rel).name.split(".")[0]
    if kind is None:
        words = len(text.split())
        if text.endswith((".", "?", "!", ":")) or words >= 7:
            kind = "status" if STATUS_FILES.search(rel) else "sentence"
        elif "Catalog" in stem and words <= 4:
            kind = "tile"
        else:
            kind = "label"
    if kind in BUDGET:
        return stem, kind, max(BUDGET[kind], -(-len(text) * 6 // 5))
    return stem, kind, max(14, -(-len(text) * 7 // 5))


def view_sources():
    """key -> the first Swift file under Sources that holds the literal, and its line."""
    texts = {p.relative_to(ROOT).as_posix(): read_source(p)
             for p in sorted((ROOT / "Sources").rglob("*.swift")) if not SKIP_DIRS & set(p.parts)}
