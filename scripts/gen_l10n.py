#!/usr/bin/env python3
"""Generates the Kit.strings files, Strings.tr.resx and the plural rule code from
l10n/shared.json, l10n/lang/<lang>.json and l10n/plural.json.

CI runs it and fails if the checked-in output differs. Every lang file is validated against
the English catalog first.

  --check         validate and scan the code, write nothing
  --samples       print language, number and category for every integer sample in plural.json
  --prune         remove keys from the lang files that the catalog no longer has
  --fmt           rewrite the lang files in catalog order, one entry per line
  --todo CODE     print what is still missing in one language
"""
import json
import re
import sys
from pathlib import Path
from xml.sax.saxutils import escape

ROOT = Path(__file__).resolve().parent.parent
CATALOG = ROOT / "l10n" / "shared.json"
LANG_DIR = ROOT / "l10n" / "lang"
LANGUAGE_LIST = ROOT / "l10n" / "languages.json"
PLURAL_RULES = ROOT / "l10n" / "plural.json"
CATEGORIES = ["zero", "one", "two", "few", "many", "other"]
STRINGS_DIRS = [ROOT / "ios" / "LazyScaniOS", ROOT / "l10n" / "mac"]
RESX = "windows/LazyScan.Core/Strings.{}.resx"
PLURAL_SWIFT = ROOT / "Sources" / "LazyScanKit" / "Localization" / "PluralRules.generated.swift"
PLURAL_CS = ROOT / "windows" / "LazyScan.Core" / "PluralRules.g.cs"
CODE = ["Sources", "windows"]
SKIP_DIRS = {"bin", "obj", "Tests", "LazyScan.Core.Tests"}
HEADER = "Generated by scripts/gen_l10n.py from l10n/shared.json; do not edit."
HEADER_PLURAL = "Generated by scripts/gen_l10n.py from l10n/plural.json; do not edit."

PLACEHOLDER = re.compile(r"\{([0-9A-Za-z_]+)\}")
CONTEXT_SUFFIX = re.compile(r"\S\|[^|\s][^|]*$")
MARKER = re.compile(r"\|(?:" + "|".join(CATEGORIES) + ")$")
LETTER = re.compile(r"[^\W\d_]")
# Names that read the same in every script.
TOKENS = re.compile("|".join(["Lazy Scan", "TWAIN", "JPEG", "TIFF", "PDF", "OCR", "PNG", "DPI", "QR", "USB"]))
LITERAL = r'"((?:[^"\\]|\\.)*)"'
# L10n.t("..."), Loc.T("..."), L10n.plural(n, one: "...") and Loc.Plural(n, "...").
CALLS = [
    (re.compile(r"\b(?:L10n\.t|Loc\.T)\(\s*" + LITERAL), (".swift", ".cs")),
    (re.compile(r"\bL10n\.plural\([^,]+,\s*one:\s*" + LITERAL + r"\s*,\s*other:\s*" + LITERAL), (".swift",)),
    (re.compile(r"\bLoc\.Plural\([^,]+,\s*" + LITERAL + r"\s*,\s*" + LITERAL), (".cs",)),
]


# "a" + "b" would be read as "a" alone, and never found at run time.
SPLIT = re.compile(r"\b(?:L10n\.t|Loc\.T)\(\s*" + LITERAL + r"\s*\+")


def placeholders(text):
    return set(PLACEHOLDER.findall(text))


def no_duplicates(pairs):
    out = {}
    for key, value in pairs:
        if key in out:
            sys.exit(f"duplicate key: {key!r}")
        out[key] = value
    return out


def read_json(path):
    return json.loads(path.read_text(encoding="utf-8"), object_pairs_hook=no_duplicates)


def categories(rules):
    """Categories a translation must cover. many is kept only with a real integer sample."""
    out = []
    for name in CATEGORIES:
        if name not in rules:
            continue
        samples = [s.strip() for s in rules[name].get("integer", "").split(",")]
        if name == "other" or any(s and "c" not in s and s != "…" for s in samples):
            out.append(name)
    return out


def languages():
    entries = read_json(LANGUAGE_LIST)
    plural = read_json(PLURAL_RULES)
    errors = []
    known = {e["code"] for e in entries}
    for path in sorted(LANG_DIR.glob("*.json")):
        if path.stem not in known:
            errors.append(f"{path.name}: not a code in languages.json")
    for entry in entries:
        code = entry["code"]
        if code not in plural:
            errors.append(f"{code}: no entry in plural.json")
        elif entry["plural"] != categories(plural[code]):
            errors.append(f"{code}: plural {','.join(entry['plural'])} differs from plural.json {','.join(categories(plural[code]))}")
    if errors:
        sys.exit("\n".join(errors))
    return {e["code"]: e for e in entries}


INFO = languages()
LANGUAGES = [code for code in INFO if (LANG_DIR / f"{code}.json").exists()]


def lang_doc(code):
    path = LANG_DIR / f"{code}.json"
    return read_json(path) if path.exists() else {"strings": {}}


def check_doc(code):
    doc = lang_doc(code)
    errors = []
    if not isinstance(doc, dict) or not isinstance(doc.get("strings", {}), dict):
        return [f"{code}: strings must be an object"]
    base = doc.get("_base")
    if base is not None and (base not in INFO or base == code):
        errors.append(f"{code}: _base {base!r} is not another language in languages.json")
    return errors


def merged_strings(code):
    """The strings of a language; a delta file (_base) is laid over the table of its base."""
    doc = lang_doc(code)
    base = doc.get("_base") or INFO[code].get("base")
    strings = merged_strings(base) if base else {}
    strings.update(doc.get("strings", {}))
    return strings


def integer_samples(lang, category):
    rules = read_json(PLURAL_RULES)[lang].get(category, {})
    return [s.strip() for s in rules.get("integer", "").split(",") if s.strip()]


def single_sample(lang, category):
    samples = integer_samples(lang, category)
    return len(samples) == 1 and "~" not in samples[0] and samples[0] != "…"


def required_categories(lang):
    """Categories a file must hold. many stays optional where its integer samples are only millions."""
    def millions(category):
        return all(s == "…" or "c" in s or s == "1000000" for s in integer_samples(lang, category))

    return [c for c in INFO[lang]["plural"] if c != "many" or not millions(c)]


def check_catalog(data):
    errors = []
    names = {}
    for key, entry in data.items():
        if not isinstance(entry, dict) or set(entry) - {"other", "note", "same"}:
            errors.append(f"{key!r}: an entry holds other, note and same only")
            continue
        if "other" in entry and not (isinstance(entry["other"], str) and entry["other"].strip()):
            errors.append(f"{key!r}: other must be text")
        if MARKER.search(key):
            errors.append(f"{key!r}: ends like a plural row name")
        forms = [key + "|" + c for c in CATEGORIES] if "other" in entry else [key]
        for name in forms:
            if names.setdefault(name.lower(), key) != key:
                errors.append(f"{key!r}: resx name collides with {names[name.lower()]!r} ignoring case")
    return errors


def check_text(value, want, omit_zero):
    if not isinstance(value, str):
        return ["must be a string"]
    if not value.strip():
        return ["is empty"]
    problems = []
    if re.search(r"[{}]", PLACEHOLDER.sub("", value)):
        problems.append("has an unbalanced brace")
    if CONTEXT_SUFFIX.search(value):
        problems.append("ends in a |context suffix")
    got = placeholders(value)
    if got != want and not (omit_zero and got == want - {"0"}):
        problems.append(f"placeholders {sorted(got)} differ from English {sorted(want)}")
    return problems


def strip_context(text):
    return text.rsplit("|", 1)[0]


def edges(text):
    return text[:len(text) - len(text.lstrip())], text[len(text.rstrip()):]


def check_language(data, lang, strings):
    """(errors, warnings, count of values equal to English) for one merged table."""
    errors, warnings, same = [], [], 0
    info = INFO[lang]
    required = required_categories(lang)

    def check_value(key, entry, value, english, category, want, omit_zero):
        nonlocal same
        label = f"{key!r}: {lang}" + (f" {category}" if category else "")
        problems = check_text(value, want, omit_zero)
        errors.extend(f"{label} {p}" for p in problems)
        if not isinstance(value, str) or not value.strip():
            return
        english = strip_context(english)
        if value == english:
            if info["latin"]:
                same += 1
            elif not (entry.get("same") is True or not LETTER.search(TOKENS.sub("", value))):
                errors.append(f"{label} is the English text")
        if value.count("\n") != english.count("\n"):
            warnings.append(f"{label} has a different number of line breaks")
        if edges(value) != edges(english):
            warnings.append(f"{label} has different leading or trailing whitespace")

    for key, value in strings.items():
        if key not in data:
            errors.append(f"{key!r}: {lang} has no English entry")
            continue
        entry = data[key]
        if "other" not in entry:
            check_value(key, entry, value, key, None, placeholders(key), False)
            continue
        if not isinstance(value, dict):
            errors.append(f"{key!r}: {lang} must hold the plural categories")
            continue
        for category in required:
            if category not in value:
                errors.append(f"{key!r}: {lang} lacks {category}")
        for category, text in value.items():
            if category not in info["plural"]:
                errors.append(f"{key!r}: {lang} has the unknown category {category}")
                continue
            check_value(key, entry, text, key if category == "one" else entry["other"], category,
                        placeholders(entry["other"]), single_sample(lang, category))
    return errors, warnings, same


def load():
    data = read_json(CATALOG)
    errors = check_catalog(data)
    tables, warnings = {}, []
    for lang in LANGUAGES:
        doc_errors = check_doc(lang)
        if doc_errors:
            errors += doc_errors
            continue
        tables[lang] = merged_strings(lang)
        found, warned, same = check_language(data, lang, tables[lang])
        errors += found
        warnings += warned
        if same:
            warnings.append(f"{lang}: {same} values are the same as English")
    for line in warnings:
        print("warning: " + line)
    if errors:
        sys.exit("\n".join(errors))
    return data, tables


def rows(data, tables, lang):
    """(key, text) pairs for one language. English has none: the call sites carry it."""
    if lang == "en":
        return
    for key in data:
        value = tables[lang].get(key)
        if value is None:
            continue
        if isinstance(value, dict):
            for category in CATEGORIES:
                if category in value:
                    yield f"{key}|{category}", value[category]
        else:
            yield key, value


def lang_text(doc, order):
    """A lang file with the strings in catalog order, one entry per line; keys the catalog lacks follow."""
    position = {key: i for i, key in enumerate(order)}
    out = []
    for name in sorted(doc, key=lambda n: n != "_base"):
        value = doc[name]
        if not isinstance(value, dict):
            out.append(f"  {json.dumps(name)}: {json.dumps(value, ensure_ascii=False)}")
            continue
        keys = sorted(value, key=lambda k: position.get(k, len(position))) if name == "strings" else list(value)
        body = ",\n".join(f"    {json.dumps(k, ensure_ascii=False)}: {json.dumps(value[k], ensure_ascii=False)}" for k in keys)
        out.append(f'  {json.dumps(name)}: {{\n{body}\n  }}' if keys else f"  {json.dumps(name)}: {{}}")
    return "{\n" + ",\n".join(out) + "\n}\n"


def format_languages(prune):
    data = read_json(CATALOG)
    for lang in LANGUAGES:
        doc = lang_doc(lang)
        if prune:
            for key in [k for k in doc["strings"] if k not in data]:
                del doc["strings"][key]
                print(f"{lang}: removed {key!r}")
        write(LANG_DIR / f"{lang}.json", lang_text(doc, list(data)))


def todo(lang):
    if lang not in INFO:
        sys.exit(f"{lang}: not in languages.json")
    data = read_json(CATALOG)
    strings = merged_strings(lang)
    required = required_categories(lang)
    for key, entry in data.items():
        have = strings.get(key)
        if "other" in entry:
            have = have if isinstance(have, dict) else {}
            need = [c for c in required if c not in have]
        else:
            need = [] if have is not None else ["text"]
        if not need:
            continue
        print(key)
        if "other" in entry:
            print(f"  plural, English other: {entry['other']}")
        print(f"  missing: {', '.join(need)}")
        if "note" in entry:
            print(f"  note: {entry['note']}")


def strings_text(pairs):
    def quote(s):
        return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'

    lines = [f"/* {HEADER} */"]
    lines += [f"{quote(k)} = {quote(v)};" for k, v in pairs]
    return "\n".join(lines) + "\n"


def resx_text(pairs):
    out = ['<?xml version="1.0" encoding="utf-8"?>', "<root>", f"  <!-- {HEADER} -->"]
    for name, value in (
        ("resmimetype", "text/microsoft-resx"),
        ("version", "2.0"),
        ("reader", "System.Resources.ResXResourceReader, System.Windows.Forms, Version=4.0.0.0, Culture=neutral, PublicKeyToken=b77a5c561934e089"),
        ("writer", "System.Resources.ResXResourceWriter, System.Windows.Forms, Version=4.0.0.0, Culture=neutral, PublicKeyToken=b77a5c561934e089"),
    ):
        out += [f'  <resheader name="{name}">', f"    <value>{value}</value>", "  </resheader>"]
    for k, v in pairs:
        out += [f'  <data name="{escape(k, {chr(34): "&quot;"})}" xml:space="preserve">', f"    <value>{escape(v)}</value>", "  </data>"]
    out.append("</root>")
    return "\n".join(out) + "\n"


def write(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(text.encode("utf-8"))


def unescape(literal):
    return re.sub(r"\\(.)", lambda m: {"n": "\n", "t": "\t"}.get(m.group(1), m.group(1)), literal)


def keys_in_code():
    found = {}
    split = set()
    for base in CODE:
        for path in (ROOT / base).rglob("*"):
            rel = path.relative_to(ROOT)
            if path.suffix not in (".swift", ".cs") or SKIP_DIRS & set(rel.parts):
                continue
            text = path.read_text(encoding="utf-8", errors="ignore")
            for pattern, suffixes in CALLS:
                if path.suffix in suffixes:
                    split.update((unescape(m.group(1)), rel.as_posix()) for m in SPLIT.finditer(text))
                    for m in pattern.finditer(text):
                        other = unescape(m.group(2)) if m.lastindex > 1 else None
                        found.setdefault(unescape(m.group(1)), (rel.as_posix(), other))
    return found, split


RULE_TOKEN = re.compile(r"\s*(?:(\d+)|([a-z]+)|(!=|\.\.|[%=,]))")


def parse_rule(text):
    """A CLDR rule as a list of 'or' alternatives, each a list of 'and' relations; None for
    the empty rule. A relation is (operand, modulus or None, negated, [(low, high), ...])."""
    tokens = []
    pos = 0
    text = text.strip()
    while pos < len(text):
        m = RULE_TOKEN.match(text, pos)
        if not m:
            sys.exit(f"plural rule {text!r}: cannot read {text[pos:]!r}")
        tokens.append(m.group(1) or m.group(2) or m.group(3))
        pos = m.end()
    if not tokens:
        return None
    at = 0

    def peek():
        return tokens[at] if at < len(tokens) else None

    def take():
        nonlocal at
        if at == len(tokens):
            sys.exit(f"plural rule {text!r}: ends too soon")
        at += 1
        return tokens[at - 1]

    def accept(token):
        if peek() == token:
            take()
            return True
        return False

    def number():
        tok = take()
        if not tok.isdigit():
            sys.exit(f"plural rule {text!r}: {tok!r} is not a number")
        return int(tok)

    def relation():
        operand = take()
        if operand not in ("n", "i", "v", "f", "t", "w", "e"):
            sys.exit(f"plural rule {text!r}: unknown operand {operand!r}")
        modulus = number() if accept("%") else None
        op = take()
        if op not in ("=", "!="):
            sys.exit(f"plural rule {text!r}: expected = or !=, found {op!r}")
        ranges = []
        while True:
            low = number()
            ranges.append((low, number() if accept("..") else low))
            if not accept(","):
                return operand, modulus, op == "!=", ranges

    alternatives = []
    while True:
        relations = [relation()]
        while accept("and"):
            relations.append(relation())
        alternatives.append(relations)
        if not accept("or"):
            break
    if peek() is not None:
        sys.exit(f"plural rule {text!r}: unexpected {peek()!r}")
    return alternatives


def holds(rule, n):
    """Whether the rule matches the integer n (v f t w e are 0)."""
    def one(relation):
        operand, modulus, negated, ranges = relation
        x = n if operand in ("n", "i") else 0
        if modulus:
            x %= modulus
        return any(low <= x <= high for low, high in ranges) != negated

    return any(all(one(r) for r in relations) for relations in rule)


def condition(rule):
    """The rule as a condition on n, written the same in Swift and C#. Relations on v f t w e
    do not depend on n and are settled here."""
    def test(x, low, high, negated):
        if low == high:
            return f"{x} {'!=' if negated else '=='} {low}"
        if negated:
            return f"({x} < {low} || {x} > {high})"
        return f"({x} >= {low} && {x} <= {high})"

    def one(relation):
        operand, modulus, negated, ranges = relation
        x = f"n % {modulus}" if modulus else "n"
        tests = [test(x, low, high, negated) for low, high in ranges]
        if len(tests) == 1:
            return tests[0]
        return "(" + (" && " if negated else " || ").join(tests) + ")"

    terms = []
    for relations in rule:
        if any(r[0] not in ("n", "i") and not holds([[r]], 0) for r in relations):
            continue
        rest = [one(r) for r in relations if r[0] in ("n", "i")]
        if not rest:
            return "true"
        terms.append(" && ".join(rest))
    return " || ".join(terms) if terms else "false"


def plural_table():
    """{language: [(category, rule, condition)]} in category order, without other."""
    table = {}
    for lang, rules in read_json(PLURAL_RULES).items():
        if lang == "cldr":
            continue
        entries = []
        for name in CATEGORIES[:-1]:
            if name in rules:
                rule = parse_rule(rules[name]["rule"])
                entries.append((name, rule, condition(rule)))
        table[lang] = entries
    return table


def plural_samples():
    """(language, n, category) for each integer sample in plural.json. Samples with a decimal
    point or an exponent other than c are left out, and so is the ellipsis."""
    for lang, rules in read_json(PLURAL_RULES).items():
        if lang == "cldr":
            continue
        for name in CATEGORIES:
            for sample in rules.get(name, {}).get("integer", "").split(","):
                sample = sample.strip()
                if not sample or sample == "…" or "." in sample or "e" in sample:
                    continue
                low, _, high = sample.partition("~")
                bounds = []
                for part in (low, high or low):
                    base, _, exp = part.partition("c")
                    bounds.append(int(base) * 10 ** int(exp or 0))
                for n in range(bounds[0], bounds[1] + 1):
                    yield lang, n, name


def check_samples():
    table = plural_table()
    errors = []
    for lang, n, name in plural_samples():
        got = next((c for c, rule, _ in table[lang] if holds(rule, n)), "other")
        if got != name:
            errors.append(f"{lang}: {n} is {got} by the rule, {name} in the samples")
    if errors:
        sys.exit("\n".join(errors))


def plural_groups():
    """Languages with the same rules together; English, which the others fall back to, last."""
    groups = {}
    for lang, entries in plural_table().items():
        groups.setdefault(tuple((name, cond) for name, _, cond in entries), []).append(lang)
    return sorted(groups.items(), key=lambda g: "en" in g[1])


def swift_plural():
    out = [f"// {HEADER_PLURAL}", "", "enum PluralCategory: String, Sendable {", "    case zero, one, two, few, many, other", "}", "",
           "enum PluralRules {",
           "    /// The CLDR cardinal category of `n`. A language without a rule uses the English one.",
           "    static func category(_ n: Int, language: String) -> PluralCategory {",
           "        switch language {"]
    for rules, langs in plural_groups():
        out.append("        default:" if "en" in langs else "        case " + ", ".join(f'"{l}"' for l in langs) + ":")
        out += [f"            if {cond} {{ return .{name} }}" for name, cond in rules if cond != "false"]
        out.append("            return .other")
    out += ["        }", "    }", "",
            "    /// Whether `language` has a rule of its own, as opposed to the English fallback.",
            "    static func hasRule(_ language: String) -> Bool {",
            "        switch language {",
            "        case " + ", ".join(f'"{l}"' for l in plural_table()) + ":",
            "            return true", "        default:", "            return false", "        }", "    }", "}"]
    return "\n".join(out) + "\n"


def cs_plural():
    out = [f"// {HEADER_PLURAL}", "", "namespace LazyScan.Core;", "",
           "// Twin of Sources/LazyScanKit/Localization/PluralRules.generated.swift.", "",
           "public static class PluralRules", "{"]
    out += [f'    public const string {c.capitalize()} = "{c}";' for c in CATEGORIES]
    out += ["", "    /// <summary>The CLDR cardinal category of <paramref name=\"n\"/>. A language without a rule uses the English one.</summary>",
            "    public static string Category(int n, string language)", "    {", "        switch (language)", "        {"]
    for rules, langs in plural_groups():
        out += ["            default:"] if "en" in langs else [f'            case "{l}":' for l in langs]
        out += [f"                if ({cond}) return {name.capitalize()};" for name, cond in rules if cond != "false"]
        out.append("                return Other;")
    out += ["        }", "    }", "",
            "    /// <summary>Whether <paramref name=\"language\"/> has a rule of its own, as opposed to the English fallback.</summary>",
            "    public static bool HasRule(string language)", "    {", "        switch (language)", "        {"]
    out += [f'            case "{l}":' for l in plural_table()]
    out += ["                return true;", "            default:", "                return false;", "        }", "    }", "}"]
    return "\n".join(out) + "\n"


def main():
    args = sys.argv[1:]
    if "--samples" in args:
        for lang, n, name in plural_samples():
            print(lang, n, name, sep="\t")
        return 0
    if "--todo" in args:
        if args.index("--todo") + 1 == len(args):
            sys.exit("usage: gen_l10n.py --todo CODE")
        todo(args[args.index("--todo") + 1])
        return 0
    if "--fmt" in args or "--prune" in args:
        format_languages("--prune" in args)
        return 0
    check_samples()
    data, tables = load()
    if "--check" not in args:
        write(PLURAL_SWIFT, swift_plural())
        write(PLURAL_CS, cs_plural())
        for lang in ["en"] + LANGUAGES:
            pairs = list(rows(data, tables, lang))
            for folder in STRINGS_DIRS:
                write(folder / f"{lang}.lproj" / "Kit.strings", strings_text(pairs))
            if lang != "en":
                write(ROOT / RESX.format(lang), resx_text(pairs))
    used, split = keys_in_code()
    unused = [k for k in data if k not in used]
    for key, path in split:
        print(f"key split with +: {key!r} ({path})")
    missing = {k: p for k, (p, _) in used.items() if k not in data}
    for key, path in missing.items():
        print(f"missing from the catalog: {key!r} ({path})")
    for key, (path, other) in used.items():
        if key in data and data[key].get("other") != other:
            print(f"plural text differs from the catalog: {key!r} ({path})")
            missing[key] = path
    for key in unused:
        print(f"in the catalog but not used in code: {key!r}")
    return 1 if missing or split or unused else 0


if __name__ == "__main__":
    sys.exit(main())
