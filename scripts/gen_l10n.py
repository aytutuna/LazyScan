def pseudo(text):
    """text with its letters accented, about 40 percent longer and wrapped in [!! !!], the opening kept clear of a sentence end for StatusLine."""
    parts, last = [], 0
    for m in KEEP.finditer(text):
        parts.append(text[last:m.start()].translate(ACCENTS))
        parts.append(m.group())
        last = m.end()
    parts.append(text[last:].translate(ACCENTS))
    pad = "~" * -(-len(LETTER.findall(text)) * 2 // 5)
    return "[!! " + "".join(parts) + pad + " !!]"


def strings_text(pairs):
    def quote(s):
        return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'

    lines = [f"/* {HEADER} */"]
    lines += [f"{quote(k)} = {quote(v)};" for k, v in pairs]
    return "\n".join(lines) + "\n"


def resx_text(pairs):
    out = ['<?xml version="1.0" encoding="utf-8"?>', "<root>", f"  <!-- {HEADER} -->"]
    for name, value in (
        ("resmimetype", "text/microsoft-resx"),
        ("version", "2.0"),
        ("reader", "System.Resources.ResXResourceReader, System.Windows.Forms, Version=4.0.0.0, Culture=neutral, PublicKeyToken=b77a5c561934e089"),
        ("writer", "System.Resources.ResXResourceWriter, System.Windows.Forms, Version=4.0.0.0, Culture=neutral, PublicKeyToken=b77a5c561934e089"),
    ):
        out += [f'  <resheader name="{name}">', f"    <value>{value}</value>", "  </resheader>"]
    for k, v in pairs:
        out += [f'  <data name="{escape(k, {chr(34): "&quot;"})}" xml:space="preserve">', f"    <value>{escape(v)}</value>", "  </data>"]
    out.append("</root>")
    return "\n".join(out) + "\n"


def write(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(text.encode("utf-8"))


def unescape(literal):
    return re.sub(r"\\(.)", lambda m: {"n": "\n", "t": "\t"}.get(m.group(1), m.group(1)), literal)


def xaml_texts(text):
    """The text of every {loc:T ...} in a XAML file. The end is found by brace depth: a text
    may hold {0}, and the markup may sit inside the StringFormat of a binding."""
    for start in re.finditer(r"\{loc:T\s", text):
        depth, i = 1, start.end()
        while i < len(text) and depth:
            if text[i] == "\\":
                i += 1
            elif text[i] == "{":
                depth += 1
            elif text[i] == "}":
                depth -= 1
            i += 1
        raw = html.unescape(text[start.end():i - 1]).strip()
        if raw.startswith("{}"):
            raw = raw[2:]
        if len(raw) > 1 and raw[0] == raw[-1] == "'":
            raw = raw[1:-1]
        yield re.sub(r"\\(.)", r"\1", raw)


def keys_in_code():
    """({key: (first file, plural others seen, platforms)}, keys split with +). The set holds None for plain sites."""
    found = {}
    split = set()

    def add(key, rel, other, platforms):
        path, others, have = found.get(key, (rel, set(), set()))
        found[key] = (path, others | {other}, have | platforms)

    for base in CODE:
        for path in (ROOT / base).rglob("*"):
            rel = path.relative_to(ROOT)
            if path.suffix not in (".swift", ".cs", ".xaml") or SKIP_DIRS & set(rel.parts):
                continue
            platforms = PLATFORMS[rel.parts[1] if base == "Sources" else base]
            text = path.read_text(encoding="utf-8", errors="ignore")
            if path.suffix == ".xaml":
                for key in xaml_texts(text):
                    add(key, rel.as_posix(), None, platforms)
                continue
            if path.suffix == ".cs":
                for m in TERNARY.finditer(text):
                    for literal in m.groups():
                        add(unescape(literal), rel.as_posix(), None, platforms)
            for pattern, suffixes in CALLS:
                if path.suffix in suffixes:
                    split.update((unescape(m.group(1)), rel.as_posix()) for m in SPLIT.finditer(text))
                    for m in pattern.finditer(text):
                        other = unescape(m.group(2)) if m.lastindex > 1 else None
                        add(unescape(m.group(1)), rel.as_posix(), other, platforms)
    return found, split


