RULE_TOKEN = re.compile(r"\s*(?:(\d+)|([a-z]+)|(!=|\.\.|[%=,]))")


def parse_rule(text):
    """A CLDR rule as a list of 'or' alternatives, each a list of 'and' relations; None for
    the empty rule. A relation is (operand, modulus or None, negated, [(low, high), ...])."""
    tokens = []
    pos = 0
    text = text.strip()
    while pos < len(text):
        m = RULE_TOKEN.match(text, pos)
        if not m:
            sys.exit(f"plural rule {text!r}: cannot read {text[pos:]!r}")
        tokens.append(m.group(1) or m.group(2) or m.group(3))
        pos = m.end()
    if not tokens:
        return None
    at = 0

    def peek():
        return tokens[at] if at < len(tokens) else None

    def take():
        nonlocal at
        if at == len(tokens):
            sys.exit(f"plural rule {text!r}: ends too soon")
        at += 1
        return tokens[at - 1]

    def accept(token):
        if peek() == token:
            take()
            return True
        return False

    def number():
        tok = take()
        if not tok.isdigit():
            sys.exit(f"plural rule {text!r}: {tok!r} is not a number")
        return int(tok)

    def relation():
        operand = take()
        if operand not in ("n", "i", "v", "f", "t", "w", "e"):
            sys.exit(f"plural rule {text!r}: unknown operand {operand!r}")
        modulus = number() if accept("%") else None
        op = take()
        if op not in ("=", "!="):
            sys.exit(f"plural rule {text!r}: expected = or !=, found {op!r}")
        ranges = []
        while True:
            low = number()
            ranges.append((low, number() if accept("..") else low))
            if not accept(","):
                return operand, modulus, op == "!=", ranges

    alternatives = []
    while True:
        relations = [relation()]
        while accept("and"):
            relations.append(relation())
        alternatives.append(relations)
        if not accept("or"):
            break
    if peek() is not None:
        sys.exit(f"plural rule {text!r}: unexpected {peek()!r}")
    return alternatives


def holds(rule, n):
    """Whether the rule matches the integer n (v f t w e are 0)."""
    def one(relation):
        operand, modulus, negated, ranges = relation
        x = n if operand in ("n", "i") else 0
        if modulus:
            x %= modulus
        return any(low <= x <= high for low, high in ranges) != negated

    return any(all(one(r) for r in relations) for relations in rule)


def condition(rule):
    """The rule as a condition on n, written the same in Swift and C#. Relations on v f t w e
    do not depend on n and are settled here."""
    def test(x, low, high, negated):
        if low == high:
            return f"{x} {'!=' if negated else '=='} {low}"
        if negated:
            return f"({x} < {low} || {x} > {high})"
        return f"({x} >= {low} && {x} <= {high})"

    def one(relation):
        operand, modulus, negated, ranges = relation
        x = f"n % {modulus}" if modulus else "n"
        tests = [test(x, low, high, negated) for low, high in ranges]
        if len(tests) == 1:
            return tests[0]
        return "(" + (" && " if negated else " || ").join(tests) + ")"

    terms = []
    for relations in rule:
        if any(r[0] not in ("n", "i") and not holds([[r]], 0) for r in relations):
            continue
        rest = [one(r) for r in relations if r[0] in ("n", "i")]
        if not rest:
            return "true"
        terms.append(" && ".join(rest))
    return " || ".join(terms) if terms else "false"


def plural_table():
    """{language: [(category, rule, condition)]} in category order, without other."""
    table = {}
    for lang, rules in read_json(PLURAL_RULES).items():
        if lang == "cldr":
            continue
        entries = []
        for name in CATEGORIES[:-1]:
            if name in rules:
                rule = parse_rule(rules[name]["rule"])
                entries.append((name, rule, condition(rule)))
        table[lang] = entries
    return table


def plural_samples():
    """(language, n, category) for each integer sample in plural.json. Samples with a decimal
    point or an exponent other than c are left out, and so is the ellipsis."""
    for lang, rules in read_json(PLURAL_RULES).items():
        if lang == "cldr":
            continue
        for name in CATEGORIES:
            for sample in rules.get(name, {}).get("integer", "").split(","):
                sample = sample.strip()
                if not sample or sample == "…" or "." in sample or "e" in sample:
                    continue
                low, _, high = sample.partition("~")
                bounds = []
                for part in (low, high or low):
                    base, _, exp = part.partition("c")
                    bounds.append(int(base) * 10 ** int(exp or 0))
                for n in range(bounds[0], bounds[1] + 1):
                    yield lang, n, name


def check_samples():
    table = plural_table()
    errors = []
    for lang, n, name in plural_samples():
        got = next((c for c, rule, _ in table[lang] if holds(rule, n)), "other")
        if got != name:
            errors.append(f"{lang}: {n} is {got} by the rule, {name} in the samples")
    if errors:
        sys.exit("\n".join(errors))


def plural_groups():
    """Languages with the same rules together; English, which the others fall back to, last."""
    groups = {}
    for lang, entries in plural_table().items():
        groups.setdefault(tuple((name, cond) for name, _, cond in entries), []).append(lang)
    return sorted(groups.items(), key=lambda g: "en" in g[1])


def swift_plural():
    out = [f"// {HEADER_PLURAL}", "", "enum PluralCategory: String, Sendable {", "    case zero, one, two, few, many, other", "}", "",
           "enum PluralRules {",
           "    /// The CLDR cardinal category of `n`. A language without a rule uses the English one.",
           "    static func category(_ n: Int, language: String) -> PluralCategory {",
           "        switch language {"]
    for rules, langs in plural_groups():
        out.append("        default:" if "en" in langs else "        case " + ", ".join(f'"{l}"' for l in langs) + ":")
        out += [f"            if {cond} {{ return .{name} }}" for name, cond in rules if cond != "false"]
        out.append("            return .other")
    out += ["        }", "    }", "",
            "    /// Whether `language` has a rule of its own, as opposed to the English fallback.",
            "    static func hasRule(_ language: String) -> Bool {",
            "        switch language {",
            "        case " + ", ".join(f'"{l}"' for l in plural_table()) + ":",
            "            return true", "        default:", "            return false", "        }", "    }", "}"]
    return "\n".join(out) + "\n"


def cs_plural():
    out = [f"// {HEADER_PLURAL}", "", "namespace LazyScan.Core;", "",
           "// Twin of Sources/LazyScanKit/Localization/PluralRules.generated.swift.", "",
           "public static class PluralRules", "{"]
    out += [f'    public const string {c.capitalize()} = "{c}";' for c in CATEGORIES]
    out += ["", "    /// <summary>The CLDR cardinal category of <paramref name=\"n\"/>. A language without a rule uses the English one.</summary>",
            "    public static string Category(int n, string language)", "    {", "        switch (language)", "        {"]
    for rules, langs in plural_groups():
        out += ["            default:"] if "en" in langs else [f'            case "{l}":' for l in langs]
        out += [f"                if ({cond}) return {name.capitalize()};" for name, cond in rules if cond != "false"]
        out.append("                return Other;")
    out += ["        }", "    }", "",
            "    /// <summary>Whether <paramref name=\"language\"/> has a rule of its own, as opposed to the English fallback.</summary>",
            "    public static bool HasRule(string language)", "    {", "        switch (language)", "        {"]
    out += [f'            case "{l}":' for l in plural_table()]
    out += ["                return true;", "            default:", "                return false;", "        }", "    }", "}"]
    return "\n".join(out) + "\n"


def view_counts(table, views, platform):
    """(translated, total) view keys of one platform."""
    texts = [view_text(k, table, views) for k, platforms in view_keys().items() if platform in platforms]
    return sum(t is not None for t in texts), len(texts)


def coverage(data, plist, used, table, info, views, lang, platform):
    """(translated, total, missing plural categories, identical to English) of one language on one platform;
    the view keys count in translated and total."""
    required = required_categories(lang)
    done = total = lacking = same = 0
    for key, entry in data.items():
        if platform not in used.get(key, (None, None, ()))[2]:
            continue
        total += 1
        value = table.get(key)
        if "other" in entry:
            have = value if isinstance(value, dict) else {}
            absent = [c for c in required if c not in have]
            lacking += len(absent)
            done += not absent
            same += sum(t == strip_context(key if c == "one" else entry["other"]) for c, t in have.items())
        else:
            done += value is not None
            same += value == strip_context(key)
    for key, english in plist.get(platform, {}).items():
        total += 1
        value = info.get(platform, {}).get(key)
        done += value is not None
        same += value == english
    view_done, view_total = view_counts(table, views, platform)
    same += sum(view_text(k, table, views) == english_view(k) for k, platforms in view_keys().items() if platform in platforms)
    return done + view_done, total + view_total, lacking, same


def listed(lang, platform):
    return platform in INFO[lang]["ship"].split(",")


def gate(data, plist, tables, infos, views, used):
    """Stops the run when a live language is not complete on a platform it ships on."""
    errors = []
    for code, entry in INFO.items():
        if code == "en" or not entry["live"]:
            continue
        for platform in PLATFORM_NAMES:
            if not listed(code, platform):
                continue
            if code not in tables:
                errors.append(f"{code}: live but has no lang file")
                break
            done, total, _, _ = coverage(data, plist, used, tables[code], infos[code], views[code], code, platform)
            if done < total:
                errors.append(f"{code}: live but only {done} of {total} are translated on {platform}")
    if errors:
        sys.exit("\n".join(errors))


def report(data, plist, tables, infos, views, used):
    print("| Language | Platform | Translated | Total | Missing plural categories | Identical to English | Views |")
    print("|---|---|---:|---:|---:|---:|---:|")
    for code in tables:
        for platform in PLATFORM_NAMES:
            if listed(code, platform):
                print(f"| {code} | {platform} | " + " | ".join(map(str, coverage(data, plist, used, tables[code], infos[code], views[code], code, platform)))
                      + " | " + "/".join(map(str, view_counts(tables[code], views[code], platform))) + " |")


def view_rows(tables, views, code, platform):
    """(key, text) pairs of Localizable.strings. English holds only the keys with a |context suffix, stripped,
    because SwiftUI looks up the whole key."""
    for key, platforms in view_keys().items():
        if platform not in platforms:
            continue
        if code == PSEUDO:
            yield key, pseudo(english_view(key))
        elif code == "en":
            if CONTEXT_SUFFIX.search(key):
                yield key, english_view(key)
        else:
            text = view_text(key, tables[code], views[code])
            if text is not None:
                yield key, text


def emit(data, plist, tables, infos, views, ship, with_pseudo):
    for platform in PLATFORM_NAMES:
        codes = ["en"] + [c for c in LANGUAGES if listed(c, platform) and (INFO[c]["live"] or not ship)]
        if with_pseudo:
            codes.append(PSEUDO)
        write(OUT / f"languages.{platform}.txt", "".join(c + "\n" for c in codes))
        for code in codes:
            pairs = list(rows(data, tables, "en" if code == PSEUDO else code))
            if code == PSEUDO:
                pairs = [(k, pseudo(v)) for k, v in pairs]
            if platform == "win":
                if code in LANGUAGES:
                    win = lang_doc(code).get("win", {})
                    pairs = [(k, win.get(k, v)) for k, v in pairs]
                write(OUT / "windows" / f"Strings.{code}.resx", resx_text(pairs))
                continue
            folder = OUT / platform / f"{code}.lproj"
            write(folder / "Kit.strings", strings_text(pairs))
            english = plist[platform]
            have = english if code in ("en", PSEUDO) else infos[code][platform]
            if code == PSEUDO:
                have = {k: pseudo(v) for k, v in have.items()}
            write(folder / "InfoPlist.strings", strings_text([(k, have[k]) for k in english if k in have]))
            write(folder / "Localizable.strings", strings_text(view_rows(tables, views, code, platform)))
    write(OUT / "mode.txt", f"ship={str(ship).lower()}" + (" pseudo=true" if with_pseudo else "") + "\n")


def main():
    args = sys.argv[1:]
    if "--samples" in args:
        for lang, n, name in plural_samples():
            print(lang, n, name, sep="\t")
        return 0
    if "--todo" in args:
        if args.index("--todo") + 1 == len(args):
            sys.exit("usage: gen_l10n.py --todo CODE")
        todo(args[args.index("--todo") + 1])
        return 0
    if "--sync" in args:
        sync("--prune" in args)
        if "--prune" in args:
            format_languages(True)
        return 0
    if "--fmt" in args or "--prune" in args:
        format_languages("--prune" in args)
        return 0
    ship = "--ship" in args
    if ship and "--pseudo" in args:
        sys.exit("--pseudo is never shipped: drop one of --ship and --pseudo")
    writes = "--check" not in args and "--report" not in args
    if writes and OUT.exists():
        shutil.rmtree(OUT)
    check_samples()
    data, plist, tables, infos, views = load()
    used, split = keys_in_code()
    if ship:
        gate(data, plist, tables, infos, views, used)
    if writes:
        write(PLURAL_SWIFT, swift_plural())
        write(PLURAL_CS, cs_plural())
        emit(data, plist, tables, infos, views, ship, "--pseudo" in args)
    unused = [k for k in data if k not in used]
    for key, path in split:
        print(f"key split with +: {key!r} ({path})")
    missing = {k: p for k, (p, _, _) in used.items() if k not in data}
    for key, path in missing.items():
        print(f"missing from the catalog: {key!r} on {','.join(sorted(used[key][2]))} ({path})")
    for key, (path, others, _) in used.items():
        if key in data and others != {data[key].get("other")}:
            print(f"plural text differs from the catalog: {key!r} ({path})")
            missing[key] = path
    for key in unused:
        print(f"in the catalog but not used in code: {key!r}")
    if "--report" in args:
        report(data, plist, tables, infos, views, used)
    return 1 if missing or split or unused else 0


if __name__ == "__main__":
    sys.exit(main())
