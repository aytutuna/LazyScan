#!/usr/bin/env python3
"""Generates the per-platform strings under l10n/out (Kit.strings, InfoPlist.strings and
Localizable.strings for ios and mac, Strings.<code>.resx for windows, the language lists and a mode
file) and the plural rule code from l10n/shared.json, l10n/lang/<lang>.json and l10n/plural.json.
A lang file may also hold a flat win section, key to text, for the few system labels where Windows
says it differently from Apple (Cancel); it overrides strings in Strings.<code>.resx only.
Localizable.strings holds the view texts: the keys the compiler found (l10n/keys-ios.json and
keys-mac.json) with the values from the views section of each lang file.

l10n/out is cleared on every run and not checked in; CI runs --check and diffs the plural rule
files. Every lang file is validated against the English catalog first.

  --check         validate and scan the code, write nothing
  --ship          emit only live languages that are complete for the platform; fail if one is not
  --pseudo        also emit qps-ploc, the English text accented, padded and wrapped in [!! !!], for
                  finding strings that skip the lookup; never with --ship
  --report        print translated, missing and identical counts per language and platform;
                  writes nothing
  --sync          append the keys the code uses and the catalog lacks; with --prune, drop unused ones
  --samples       print language, number and category for every integer sample in plural.json
  --prune         remove keys from the lang files that the catalog no longer has
  --fmt           rewrite the lang files in catalog order, one entry per line
  --todo CODE     print what is still missing in one language, each key with its file, screen, class,
                  width budget and note
"""
